export type Lang = "en" | "hi";

/** Text in a fixed language (staff screens are English whatever the candidate toggle says). */
export function translate(lang: Lang, k: Key, vars?: Record<string, string | number>) {
  let s = (lang === "hi" ? hi : en)[k] ?? en[k] ?? k;
  for (const [n, v] of Object.entries(vars || {})) s = s.replace(`{${n}}`, String(v));
  return s;
}
type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string };
const I18n = createContext<Ctx>(null as unknown as Ctx);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (store.get("fp-lang") === "hi" ? "hi" : "en"));
  const setLang = (l: Lang) => { setLangState(l); store.set("fp-lang", l); };
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const t = (k: Key, vars?: Record<string, string | number>) => translate(lang, k, vars);
  return <I18n.Provider value={{ lang, setLang, t }}>{children}</I18n.Provider>;
}

export const useT = () => useContext(I18n);
