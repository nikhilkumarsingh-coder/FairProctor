"""Render artifacts/metrics.json as reports/RESULTS.md (python -m fairproctor.report)."""
import json
import os
import sys


def pct(x):
    return f"{100 * x:.1f}%"


def render(m: dict) -> str:
    h = m["holdout_policy"]
    f = m["false_flag_rate_by_bandwidth"]
    v = m["one_frame_per_5s"]
    lines = [
        "# Results on the labelled sample",
        "",
        f"{m['n_sessions']:,} sessions, {m['n_confirmed']} confirmed malpractice. Every number below is **out of fold**: "
        "each session was scored by a model trained on the other sittings (5-fold, grouped by sitting, so a collusion ring "
        "never straddles train and test). Data is synthetic, generated by `data/generate.py`; see README for what that does and does not prove.",
        "",
        "## Done-when checklist",
        "",
        "| Criterion | Result |",
        "|---|---|",
        f"| Cut the review queue by at least half while surfacing every confirmed case | Out-of-fold ranking: all {m['n_confirmed']} confirmed cases are in the top "
        f"{pct(m['queue_at_full_recall'])} of sessions — a **{pct(1 - m['queue_at_full_recall'])} cut** vs the old rules, which flag {pct(m['legacy_queue_fraction'])} of sessions. "
        f"Stricter test, threshold set without seeing the fold: {pct(h['queue_fraction'])} queued, {h['recall'] * 100:.2f}% recall ({h['missed']} missed). |",
        f"| Every flag links to the moments that caused it | {pct(m['flagged_sessions_with_linked_moments'])} of queued sessions have time-stamped moments; "
        f"{pct(m['flagged_sessions_with_any_explanation'])} have a written reason. |",
        f"| Usable score at one frame every 5 s | AUC {v['auc']} (full video: {m['auc']}); every confirmed case still above the threshold "
        f"(recall {pct(v['recall_at_threshold'])}); rank correlation with the full-video score {v['rank_correlation_with_full_video']}. |",
        "| Pre-check runs in a phone browser, plain-language fixes | `/precheck` — tested at 390 px wide; English and Hindi. |",
        f"| False-flag rate reported separately for low-bandwidth and normal | Low: {pct(f['low']['ours'])}, normal: {pct(f['normal']['ours'])} "
        f"(old rules at the same queue size: low {pct(f['low']['legacy_same_queue_size'])}, normal {pct(f['normal']['legacy_same_queue_size'])}). |",
        "",
        "## Top of the queue (what the judges weight most)",
        "",
        "| First N sessions | Precision (ours) | Precision (old rules, ranked by flag rate) |",
        "|---|---|---|",
    ]
    for k, p in m["precision_at_k"].items():
        lines.append(f"| {k} | {pct(p)} | {pct(m['legacy_precision_at_k'][k])} |")
    rf = m["review_first"]
    lines += [
        "",
        f"The **Review first** band holds the top {rf['n']} sessions at {pct(rf['precision'])} precision. "
        f"AUC {m['auc']}, average precision {m['average_precision']}.",
        "",
        "## Fairness: honest sessions sent to review",
        "",
        "| Group | Ours | Old rules, same queue size |",
        "|---|---|---|",
        f"| Low bandwidth ({f['low']['honest_sessions']:,} honest) | {pct(f['low']['ours'])} | {pct(f['low']['legacy_same_queue_size'])} |",
        f"| Normal bandwidth ({f['normal']['honest_sessions']:,} honest) | {pct(f['normal']['ours'])} | {pct(f['normal']['legacy_same_queue_size'])} |",
        f"| Phone | {pct(m['false_flag_rate_by_device']['phone'])} | |",
        f"| Desktop | {pct(m['false_flag_rate_by_device']['desktop'])} | |",
        "",
        "The old rules flag low-bandwidth candidates about twice as often because blurry, sparse video produces more "
        "\"face not visible\" and \"looking away\" frames. Our gap is a few points. The remaining gap comes from less video "
        "to clear a candidate, not from video counting against them: missing video is fixed to the honest baseline before scoring.",
        "",
        "These rates are high in absolute terms because the queue is sized to catch *every* confirmed case. Reviewers "
        f"should work the **Review first** band first: it holds {rf['n']} sessions ({pct(rf['n'] / m['n_sessions'])} of all) and "
        f"{pct(rf['n'] * rf['precision'] / m['n_confirmed'])} of the confirmed cases.",
        "",
        "## Recall by malpractice pattern (deployed threshold)",
        "",
        "| Pattern | Full video | One frame / 5 s |",
        "|---|---|---|",
    ]
    for t, r in m.get("recall_by_type", {}).items():
        lines.append(f"| {t.replace('_', ' ')} | {pct(r)} | {pct(v['recall_by_type'].get(t, 0))} |")
    lines += [
        "",
        "## CPU cost",
        "",
        f"Model training: {m['train_seconds']} s on 2 CPU cores. Scoring from features: {m['cpu_scoring_ms_per_session']} ms per session. "
        "Live scoring through the API (including comparing answers against the ~200 other candidates in the sitting): about 2 s per session.",
    ]
    return "\n".join(lines) + "\n"


def render_events_only(m: dict) -> str:
    """The same evaluation on event logs alone (answer timing, focus, paste, shared answers; no video)."""
    h = m["holdout_policy"]
    f = m["false_flag_rate_by_bandwidth"]
    q = m.get("queue_at_recall", {})
    met = m["queue_at_full_recall"] <= 0.5
    lines = [
        "# Results on event logs only (no video)",
        "",
        f"{m['n_sessions']:,} sessions, {m['n_confirmed']} confirmed malpractice, scored from answer timing, focus changes, "
        "paste events and identical wrong answers only: the shape of the problem statement's labelled dataset, which has "
        "no video. Every number is **out of fold** (5-fold, grouped by sitting). On the synthetic data the video frames were "
        "removed before building features and the model was trained without the camera inputs.",
        "",
        "## Done-when: cut the queue by at least half while surfacing every confirmed case",
        "",
        f"**{'Met' if met else 'Not met'} on event logs alone.** All {m['n_confirmed']} confirmed cases are in the top "
        f"{pct(m['queue_at_full_recall'])} of sessions (stricter test, threshold set without seeing the fold: "
        f"{pct(h['queue_fraction'])} queued, {h['missed']} missed). With video the same pipeline needs 44.9% "
        "(`RESULTS.md`).",
        "",
        "| Confirmed cases caught | Share of sessions to review |",
        "|---|---|",
    ]
    for r, v in q.items():
        lines.append(f"| {int(float(r) * 100)}% | {pct(v)} |")
    lines += [f"| 100% | {pct(m['queue_at_full_recall'])} |", "",
              f"Reviewing the top half of the queue catches **{pct(m['recall_in_top_half'])}** of confirmed cases.", ""]
    if m.get("recall_in_top_half_by_type"):
        lines += ["| Pattern | Caught in the top half |", "|---|---|"]
        lines += [f"| {t.replace('_', ' ')} | {pct(r)} |" for t, r in m["recall_in_top_half_by_type"].items()]
        lines.append("")
    lines += [
        "## Top of the queue",
        "",
        "| First N sessions | Precision | Old rules (flag rate) |",
        "|---|---|---|",
    ]
    for k, p in m["precision_at_k"].items():
        lines.append(f"| {k} | {pct(p)} | {pct(m['legacy_precision_at_k'][k])} |")
    rf = m["review_first"]
    lines += [
        "",
        f"Review first: top {rf['n']} sessions at {pct(rf['precision'])} precision. AUC {m['auc']}, average precision {m['average_precision']}.",
        "Without video the old rules reduce to counting focus losses. At the very top of the queue that can be more precise, "
        "because searching in another tab always leaves focus losses; further down the queue the model is far ahead.",
        "",
        "## Fairness: honest sessions sent to review (at the catch-everything threshold)",
        "",
        f"Low bandwidth: {pct(f['low']['ours'])}; normal: {pct(f['normal']['ours'])}. Bandwidth and device are not model inputs.",
        "",
        "## Why event logs alone cannot surface every case",
        "",
        "Answers relayed from a second phone or a helper are mostly *correct*, so they raise the candidate's own "
        "estimated ability, and on event logs alone that candidate looks like a strong honest one. Collusion (shared wrong "
        "answers) and tab searching with pastes leave clear traces in the logs; a second phone and a helper mostly do not. "
        "We tried answer-timing features from the test-security literature on top of these (a block of answers far above "
        "the candidate's level, long pauses then correct answers on hard questions); out of fold they did not move the "
        "catch-everything queue below half, so they were not added. Reaching the target on real event logs would need "
        "signals the synthetic logs do not carry, or the video and frame samples. This is reported, not tuned around.",
        "",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "artifacts/metrics.json"
    m = json.load(open(src))
    os.makedirs("reports", exist_ok=True)
    open("reports/RESULTS.md", "w").write(render(m))
    print("wrote reports/RESULTS.md")
